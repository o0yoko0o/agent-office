#!/usr/bin/env bash
# Writes compose.mounts.yaml: a read-only bind mount, at the same path, for
# every agent transcript folder that exists on this machine (the roots from
# src/ingest/discover.ts), plus AGENT_OFFICE_<AGENT>_DIR overrides from the
# environment, plus the host's MCP outbox at $AGENT_OFFICE_HOME/outbox in the
# container. Folders that don't exist are skipped, so Docker never creates
# them on the host. Nothing on the host is written except the output file.
#
# Usage: scripts/docker/mounts.sh [output file, default compose.mounts.yaml]
set -euo pipefail

out="${1:-compose.mounts.yaml}"
home="${HOME:?HOME is not set}"
container_office_home=/var/lib/agentoffice

sources=()
targets=()
envs=()

mount() { # source [target]
  [ -e "$1" ] || return 0
  sources+=("$1")
  targets+=("${2:-$1}")
}

for d in .claude/projects .claude/sessions .commandcode/projects .codex/sessions .factory/sessions \
  .qwen/projects .cursor/projects .gemini/tmp .cache/.gemini/tmp .local/share/opencode; do
  mount "$home/$d"
done

for agent in CLAUDE COMMANDCODE CODEX DROID QWEN CURSOR GEMINI OPENCODE; do
  var="AGENT_OFFICE_${agent}_DIR"
  val="${!var:-}"
  [ -n "$val" ] || continue
  envs+=("$var=$val")
  # opencode's override may name the database file; its -wal and -shm live beside it.
  if [ "$agent" = OPENCODE ] && [[ "$val" == *.db ]]; then val="$(dirname "$val")"; fi
  mount "$val"
done

host_outbox="${AGENT_OFFICE_HOME:-$home/.agentoffice}/outbox"
mount "$host_outbox" "$container_office_home/outbox"

q() { # YAML double-quoted string
  local s="${1//\\/\\\\}"
  printf '"%s"' "${s//\"/\\\"}"
}

{
  echo "# Generated by scripts/docker/mounts.sh. Do not edit, run \`make up\` instead."
  echo "services:"
  echo "  office:"
  if [ ${#envs[@]} -gt 0 ]; then
    echo "    environment:"
    for e in "${envs[@]}"; do echo "      ${e%%=*}: $(q "${e#*=}")"; done
  fi
  if [ ${#sources[@]} -gt 0 ]; then
    echo "    volumes:"
    for i in "${!sources[@]}"; do
      echo "      - type: bind"
      echo "        source: $(q "${sources[$i]}")"
      echo "        target: $(q "${targets[$i]}")"
      echo "        read_only: true"
    done
  else
    echo "    {}"
  fi
} > "$out"

echo "Mounts (read-only): ${#sources[@]} folder(s) written to $out"
[ -e "$host_outbox" ] || echo "Note: no MCP outbox at $host_outbox yet. Run \`make up\` again once an agent has used an office tool."
